def apply_test_mode(test_mode, UAPSID, base_res_dir, dir_stamp, obid_val):
    """
    Ad-hoc test runs (--test_mode): a manual aps_runner.py invocation against a pair of L1
    files that still submits real SLURM jobs, but shouldn't be mistaken
    for - or land in the same directory as - an official product.

    If test_mode is set:
      - forces a TEST_-prefixed tag (auto-generated if UAPSID wasn't
        given, otherwise the given one is prefixed if not already) - this
        becomes JOB_ID_HEADNAME same as a real uapsid would, so every job
        in the chain is unmistakable in squeue (e.g. RR_L2_TEST_...) and
        immediately trackable with `squeue --name <tag>`.
      - redirects output into <base_res_dir>/TEST/<dir_stamp>_<obid>_<tag>/
        instead of the real <base_res_dir>/<dir_stamp>/<obid>/ - so a test
        run can never land in, or collide with, a real OB's directory.
        Safe to bulk `rm -rf <base_res_dir>/TEST/` whenever convenient.

    Returns (uapsid, outpath) - outpath is None when test_mode is False,
    meaning "use the normal per-OB path" (unchanged behavior).
    """
    if not test_mode:
        return UAPSID, None

    if UAPSID is None or str(UAPSID).strip().upper() in ('NONE', ''):
        tag = 'TEST_' + datetime.datetime.now().strftime('%Y%m%d%H%M%S') + '_' + uuid.uuid4().hex[:6]
    else:
        tag = str(UAPSID).strip()
        if not tag.upper().startswith('TEST'):
            tag = 'TEST_' + tag

    outpath = Path(base_res_dir).joinpath('TEST').joinpath(f"{dir_stamp}_{obid_val}_{tag}")
    print(f"[TEST MODE] tag={tag}  output directory={outpath}")
    return tag, outpath

