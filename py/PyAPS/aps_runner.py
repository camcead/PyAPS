    # ------------------------------------------------------------------ #
    # IFU_Gal
    # Note: FERRE_EXE, FERRE_TEMPLATES, RVS_CONFIG are passed explicitly
    # so they appear in the generated script for transparency.
    # They are also present in the IFU_params JSON — the worker uses
    # the argument value as an override if provided, otherwise falls
    # back to the JSON. Passing them here ensures the script is
    # self-contained and auditable.
    # ------------------------------------------------------------------ #
