def update_arms_ratio(infiles, res_mode, camera, arms_ratio, GR_ratio_HR=0.85, BR_ratio_HR=0.85, GR_ratio_LR=1.0, BR_ratio_LR=1.0):
    """
    Updates the `arms_ratio` list based on the camera configuration and resolution mode.

    This function adjusts `arms_ratio` depending on the camera types specified in `camera` and the resolution mode
    (`res_mode`). If the resolution mode is 'HR' (high-resolution), specific ratios for 'GREEN' and 'BLUE' cameras
    (`GR_ratio_HR`, `BR_ratio_HR`) are applied. If the resolution mode is 'LR' (low-resolution), the ratios `GR_ratio_LR`
    and `BR_ratio_LR` are applied instead. Ratios are only updated if there is more than one file in `infiles`.

    Parameters:
    - infiles (list): List of file paths; function only modifies `arms_ratio` if there is more than one file.
    - res_mode (list): List of resolution modes. Function checks for 'HR' or 'LR' to determine the ratio adjustments.
    - camera (list): List of cameras used, e.g., ['GREEN', 'RED']. The order of cameras affects the updated ratios.
    - arms_ratio (list): Initial list of ratios for the cameras, which will be updated based on the `camera` list.
    - GR_ratio_HR (float): Ratio to apply for 'GREEN' in HR mode. Default is 0.85.
    - BR_ratio_HR (float): Ratio to apply for 'BLUE' in HR mode. Default is 0.85.
    - GR_ratio_LR (float): Ratio to apply for 'GREEN' in LR mode. Default is 1.0.
    - BR_ratio_LR (float): Ratio to apply for 'BLUE' in LR mode. Default is 1.0.

    Returns:
    - list: Updated `arms_ratio` based on the camera types and given ratios. If conditions are not met, returns the original `arms_ratio`.
    """

    # Check if there is more than one file and if any specified res_mode (HR or LR) is applicable
    if len(infiles) > 1:
        # Determine which ratio set to use based on res_mode
        if 'HR' in res_mode:
            # Set camera ratios for high-resolution mode
            camera_ratios = {
                'GREEN': round(1.0 / GR_ratio_HR,2),  # Apply the HR ratio for GREEN
                'BLUE': round(1.0 / BR_ratio_HR,2),   # Apply the HR ratio for BLUE
                'RED': 1.0                   # Default 1.0 for RED
            }
        elif 'LR' in res_mode:
            # Set camera ratios for low-resolution mode
            camera_ratios = {
                'GREEN': round(1.0 / GR_ratio_LR,2),  # Apply the LR ratio for GREEN
                'BLUE': round(1.0 / BR_ratio_LR,2),   # Apply the LR ratio for BLUE
                'RED': 1.0                   # Default 1.0 for RED
            }
        else:
            # If res_mode is neither 'HR' nor 'LR', return with a warning and no changes
            print(f'[WARNING] - Unsupported res_mode: {res_mode} detected in update_arms_ratio function')
            print('[DEBUG] - No changes applied to arms_ratio')
            return arms_ratio

        # Update `arms_ratio` based on the camera list
        # For each camera, retrieve the corresponding ratio from `camera_ratios`.
        # If a camera type is not in `camera_ratios`, default to 1.
        arms_ratio = [camera_ratios.get(cam, 1) for cam in camera]
    else:
        # If there's only one file, print debug info and return the original arms_ratio
        print('[DEBUG] - No changes applied to arms_ratio (single file in infiles)')

    # Return the updated list of ratios
    return arms_ratio

