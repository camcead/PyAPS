def get_ifu_param_allow_none(conf_json, conf_yaml, key, default):
    """
    Same JSON > YAML > hardcoded-default priority as get_ifu_param, EXCEPT
    an explicit 'None'/'null' in the IFU_params JSON is NOT treated as
    "not set, fall through" -- it is passed down as the literal string
    'None', which aps_ifu_prepare.py/aps_ifu_seg3d.py interpret as "measure
    the optimal value from the data itself" (see
    aps_ifu_seg3d.estimate_seg2d_params) rather than falling back to the
    YAML/hardcoded numeric default.

    Use this ONLY for keys the downstream script actually knows how to
    handle a literal None for (currently: seg2d_ext_thresh, seg2d_minarea
    -- both feed estimate_seg2d_params, auto-estimating from data;
    seg2d_deblend_nthresh -- resolves to a fixed default, deliberately not
    data-driven, see aps_ifu_prepare.ifu_seg2d.__init__;
    seg3d_merge_group_min_lines -- None DISABLES the multi-line merge path
    entirely; seg3d_merge_extreme_safety_margin -- None DISABLES the
    extreme-S/N merge path entirely; see aps_ifu_seg3d.merge_into_patch_
    table). For every other
    key, plain get_ifu_param (where JSON 'None' means "not set, use
    YAML/default") is correct -- do not swap it in without checking the
    receiving code actually handles a None value.
    """
    if conf_json is not None and key in conf_json and conf_json[key] is not None:
        val = str(conf_json[key]).strip()
        if val.lower() in ('none', 'null'):
            print(f"  {key}: from IFU_params JSON = None -> will auto-estimate from data")
            return 'None'
    return get_ifu_param(conf_json, conf_yaml, key, default)
