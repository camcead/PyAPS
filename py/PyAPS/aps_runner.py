def check_path(aps_path, create=False, verbos=True):
    if not aps_path.exists():
        if verbos:
            print('PATH CHECK: Failed: %s does not exist' %aps_path)
        if create:
            aps_path.mkdir(parents=True)
            if verbos:
                print('PATH CHECK: CREATING %s' %aps_path)

            check_path(aps_path, create=False, verbos=False)
        else:
            sys.exit('check_path module failed')
    else:
        if verbos:
            print('PATH CHECK: Done!  %s' %aps_path)

