def get_ifu_param(conf_json, conf_yaml, key, default):
    """
    Resolve a parameter value with priority:
      1. IFU_params JSON  (conf_json)
      2. script_params YAML (conf_yaml)
      3. hardcoded default

    Parameters
    ----------
    conf_json : dict
        Loaded IFU_params JSON (e.g. LIFULR11.json). May be None.
    conf_yaml : dict
        Loaded script_params YAML (conf).
    key : str
        Parameter key to look up.
    default : str
        Hardcoded fallback value (as string).

    Returns
    -------
    str
        Resolved value as a string, ready for insertion into a shell command.
    """
    if conf_json is not None and key in conf_json and conf_json[key] is not None:
        val = str(conf_json[key]).strip()
        if val.lower() not in ('none', 'null', ''):
            print(f"  {key}: from IFU_params JSON = {val}")
            return val

    if key in conf_yaml and conf_yaml[key] is not None:
        val = str(conf_yaml[key]).strip()
        if val.lower() not in ('none', 'null', ''):
            print(f"  {key}: from script_params YAML = {val}")
            return val

    print(f"  {key}: using hardcoded default = {default}")
    return default
