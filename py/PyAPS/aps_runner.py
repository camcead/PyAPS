def scriptGen_runner(options=None):

    parser = argparse.ArgumentParser(description="RUN FERRE for WEAVE target spectra.")

    parser.add_argument("--infiles", type=none_or_str, default=None,
        required=True, help="input fits files (L1)", nargs='*')

    parser.add_argument("--aps_ids", type=none_or_str, default=None,
        required=False, help="comma-separated list of WEAVE APS_IDs")

    parser.add_argument("--config_file", type=none_or_str, default=None,
        required=False, help="config file, contains all default parameters in YAML foramt")

    parser.add_argument("--cat_list", type=none_or_str, default=None,
        required=True, help=" comma seperated list of catalog files, contains original input data")

    parser.add_argument("--targsrvy", type=none_or_str, default=None,
        required=False, help="comma-separated list of surveys to be considered")

    parser.add_argument("--targclass", type=none_or_str, default=None,
        required=False, help="comma-separated list of classtypes to be considered")

    parser.add_argument("--mask_aps_ids", type=none_or_str, default=None,
        required=False, help="comma-separated list of APS_IDs to be masked")

    parser.add_argument("--area", type=none_or_str, default=None,
        required=False, help="The area in [RA(deg), DEC(deg), RADIUS(arcsec)] to be considered in analysis")

    parser.add_argument("--mask_areas", type=none_or_str, default=None,
        required=False, help="The multi area(s) in [RA(deg), DEC(deg), Radius(arcsec)] to be excluded from analysis", nargs='*')

    parser.add_argument("--wlranges", type=none_or_str, default=None,
        required=False, help="wavelength range array for each elements of the setup", nargs='*')

    parser.add_argument("--mod_wlranges", type=str2bool, default=False,
        required=False, help="if True, use the wlranges read from the config file")

    parser.add_argument('--hname_suffix',
        help='Output headname suffix. to be added into the end of the generated headname',
        type=none_or_str, default=None, required=False)

    parser.add_argument('--headname',
        help='headname to be used',
        type=none_or_str, default=None, required=False)

    parser.add_argument('--uapsid',
        help='unique id to be used for the jobnames in APS database/repository ',
        type=none_or_str, default=None, required=False)

    parser.add_argument("--arms_ratio", type=none_or_str, default=None,
        required=False, help="Correction (flux and ivar/error) faction for each arms")

    parser.add_argument("--log", type=str2bool, default=False,
        required=False, help="if True, all logs will be recorded in a automatically generated log file")

    parser.add_argument("--aps_ovr", type=str2bool, default=False,
        required=False, help="if True, it will overwrite the final APS product")

    parser.add_argument("--CS_ovr", type=str2bool, default=False,
        required=False, help="if True, it will overwrite the final CS products")

    parser.add_argument("--run_CS", type=str2bool, default=True,
        required=False, help="if True, try CS code, if possible")

    parser.add_argument("--run_L2", type=str2bool, default=True,
        required=False, help="if True, try running L2")

    parser.add_argument("--CPS_path", type=str2bool, default=True,
        required=False, help="if True, it generate the output path from the original L1 file. Otherwise, it will be generated from the OBSDATE from L1 header")

    parser.add_argument("--test_mode", type=str2bool, default=False,
        required=False, help="Ad-hoc test run: forces a TEST_-prefixed job tag (auto-generated if "
        "--uapsid wasn't given) and redirects output into <PyAPS_RES|CS_RES>/TEST/... instead of "
        "the real per-OB directory, so a manual test submission (e.g. with --hpc 3) is trackable "
        "via SLURM (e.g. squeue --name <tag>) without ever being mistaken for, or landing alongside, an "
        "official product.")

    parser.add_argument('--mp_MOS',
         help='Number of threads (CPUs) to be used. It can be a single value or a list for each module [RR,RVS,FR,PPXF,EMI,LS,L2M]',
        required=False, type=none_or_str, default=None)

    parser.add_argument('--mp_LIFU',
         help='Number of threads (CPUs) to be used in LIFU MODE (IN LR res) For HR we double it. It can be a single value or a list for each module [PR, EXGAL, GAL]',
        required=False, type=none_or_str, default=None)

    parser.add_argument('--mp_MIFU',
         help='Number of threads (CPUs) to be used in MIFU MODE (IN LR res) For HR we double it. It can be a single value or a list for each module [PR, EXGAL, GAL]',
        required=False, type=none_or_str, default=None)


    parser.add_argument('--mp_CS',
         help='Number of threads (CPUs) to be used. It can be a single value or a list for each module [SQ, FESWI,SPACE,AMY,AN, RRLGV, RRLEW]',
        required=False, type=none_or_str, default=None)

    parser.add_argument('--hpc', help='Running mode 0: Creates scripts only, 1: bash, 2:kiko 3: slurm', type=int, default=0)



    ## IFU dedicated params

    parser.add_argument("--seg2d_white_images", type=none_or_str, default=None,
        required=False, help="comma-separated list of input white_images to be deployed for 2D segmentation")

    parser.add_argument('--patch_file',
        help='full path to the patch file contains desired extraction info (ellipse and class params)',
        type=none_or_str, default=None, required=False)


    ## Check if any command-line argument has been passed to the module. It counts the number of system arguments to check this.
    args = None
    if len(sys.argv) > 1:
        args = parser.parse_args()
    else:
        print('---------------------------------------------------------------------------------')
        print('No command-line argument has been passed to this module. Running DEMO/DEBUG mode!')
        print('---------------------------------------------------------------------------------')

        args = parser.parse_args(options)

    # test_mode: resolve ONE shared tag up front, so if both --run_L2 and
    # --run_CS are requested for the same call, they end up under the same
    # trackable tag instead of each apply_test_mode() call (inside
    # mos/ifu/cs_scriptGEN) independently generating its own.
    if args.test_mode and (args.uapsid is None or str(args.uapsid).strip().upper() == 'NONE'):
        args.uapsid = 'TEST_' + datetime.datetime.now().strftime('%Y%m%d%H%M%S') + '_' + uuid.uuid4().hex[:6]
        print(f"[TEST MODE] auto-generated tag: {args.uapsid}")

    wlranges = None
    if args.wlranges[0] is not None:
        wlranges=[]
        for i in range(len(args.infiles)):
            wlranges.append([float(x) for x in args.wlranges[i].split(",")])

    elif args.mod_wlranges:
        wlranges=[]
        ### READ Config file
        conf_tmp = read_yaml_config(args.config_file)

        for i in range(len(args.infiles)):
            l1_info_i = l1_fileinfo([args.infiles[i]])
            # generate keys searchable in the confile file. e.g. LIFU_LR_BLUE or MOS_HR_RED
            key_txt = '_'.join([l1_info_i['mode'],l1_info_i['res_mode'][0],l1_info_i['camera'][0]]).upper().replace(" ", "")
            try:
                wlranges.append([float(x) for x in conf_tmp[key_txt].split(",")])
                print(f'DEBUG: Modified wavelength used.')
            except:
                print(f'WARNING: No Modified wavelength range found for the setup: {key_txt}. Using the default range instead.')
                wlranges.append(l1_info_i['wlranges'][0])
            del l1_info_i
        # update the args.wlranges for further reporting/loggimg
        args.wlranges = wlranges


    cat_list = None
    if args.cat_list is not None:
        cat_list = [ str(x).strip() for x in args.cat_list.split(",") ]

    arms_ratio = None
    if args.arms_ratio is not None:
        arms_ratio = [ float(x) for x in args.arms_ratio.split(",") ]

    aps_ids = None
    if args.aps_ids is not None:
        aps_ids = np.array(args.aps_ids.split(","), dtype=np.int32).tolist()

    targsrvy = None
    if args.targsrvy is not None:
        targsrvy = [ str(x) for x in args.targsrvy.split(",") ]

    targclass = None
    if args.targclass is not None:
        targclass = [ str(x) for x in args.targclass.split(",") ]

    mask_aps_ids = None
    if args.mask_aps_ids is not None:
        mask_aps_ids = np.array(args.mask_aps_ids.split(","), dtype=np.int32).tolist()

    ## area and mask_area are not applicable in the IFU mode, so we put them in a try-exception to avoid any issue
    try:
        area = None
        if args.area is not None:
            area = [float(x) for x in args.area.split(",")]
            ## also update the args.area to be printed in the final format in the report file
            args.area=area
    except:
        area = None
        args.area=area
    try:
        mask_areas = None
        if args.mask_areas[0] is not None:
            mask_areas =[]
            for i in range(len(args.mask_areas)):
                mask_areas.append([float(x) for x in args.mask_areas[i].split(",")])
            ## also update the args.mask_areas to be printed in the final format in the report file
            args.mask_areas=mask_areas
    except:
        mask_areas = None
        args.mask_areas=mask_areas


    ## Taking care of MP_MOS param. (a single value to be used for all modules or a list of INTs for each module)
    if args.mp_MOS is None: args.mp_MOS=1
    mp_list = [ int(mpn) for mpn in str(args.mp_MOS).split(",") ]
    # if a single value, then a list will be generated accordingly.
    if len(mp_list) == 1: mp_list= mp_list * n_modules_MOS
    # if a list passed, it checks its length.
    assert len(mp_list) == n_modules_MOS , 'input mp param must be a single value of a list of length %s for MOS mode' %(str(n_modules_MOS))
    # update args.mp
    args.mp_MOS = mp_list


    ## Taking care of MP_LIFU param. (a single value to be used for all modules or a list of INTs for each module)
    if args.mp_LIFU is None: args.mp_LIFU=1
    mp_list = [ int(mpn) for mpn in str(args.mp_LIFU).split(",") ]
    # if a single value, then a list will be generated accordingly.
    if len(mp_list) == 1: mp_list= mp_list * n_modules_LIFU
    # if a list passed, it checks its length.
    assert len(mp_list) == n_modules_LIFU , 'input mp param must be a single value of a list of length %s for IFU mode' %(str(n_modules_LIFU))
    # update args.mp
    args.mp_LIFU = mp_list


    ## Taking care of MP_MIFU param. (a single value to be used for all modules or a list of INTs for each module)
    if args.mp_MIFU is None: args.mp_MIFU=1
    mp_list = [ int(mpn) for mpn in str(args.mp_MIFU).split(",") ]
    # if a single value, then a list will be generated accordingly.
    if len(mp_list) == 1: mp_list= mp_list * n_modules_MIFU
    # if a list passed, it checks its length.
    assert len(mp_list) == n_modules_MIFU , 'input mp param must be a single value of a list of length %s for IFU mode' %(str(n_modules_MIFU))
    # update args.mp
    args.mp_MIFU = mp_list





    ## Taking care of MP_CS param. (a single value to be used for all modules or a list of INTs for each module)
    if args.mp_CS is None: args.mp_CS=1
    mp_list = [ int(mpn) for mpn in str(args.mp_CS).split(",") ]
    # if a single value, then a list will be generated accordingly.
    if len(mp_list) == 1: mp_list= mp_list * n_modules_CS
    # if a list passed, it checks its length.
    assert len(mp_list) == n_modules_CS , 'input mp param must be a single value of a list of length %s for CS mode' %(str(n_modules_CS))
    # update args.mp
    args.mp_CS = mp_list



    seg2d_white_images = None
    if args.seg2d_white_images is not None:
        seg2d_white_images = [str(x) for x in args.seg2d_white_images.split(",")]



    ## print input arguments on the screen
    for argp in vars(args):
        print('Par: %-20s val: %s'%(argp, getattr(args, argp)))


    ## Here we check if the data mode is among those working modes with MOS-like structure
    l1_info = l1_fileinfo([args.infiles[0]])
    # prepare the default value for the script param
    script_full_path = dict()
    if 'MOS' in l1_info['mode']:
        if args.run_L2:
            script_full_path['MOS'] = mos_scriptGEN(args.infiles, args.config_file, cat_list =cat_list ,aps_ids=aps_ids, wlranges=wlranges ,targsrvy=targsrvy,  targclass=targclass,
                mask_aps_ids=mask_aps_ids, area=area, mask_areas=mask_areas, arms_ratio=arms_ratio, headname = args.headname, hname_suffix=args.hname_suffix, log = args.log, aps_ovr =args.aps_ovr, mp=args.mp_MOS, UAPSID= args.uapsid, hpc=args.hpc, CPS_path=args.CPS_path, test_mode=args.test_mode)
        if args.run_CS:
            script_full_path['CS'] = cs_scriptGEN(args.infiles, args.config_file, cat_list =cat_list, aps_ids=aps_ids, wlranges=wlranges, mask_aps_ids=mask_aps_ids, area=area, mask_areas=mask_areas, arms_ratio=arms_ratio,
                headname = args.headname, hname_suffix=args.hname_suffix, log=args.log, CS_ovr=args.CS_ovr, mp = args.mp_CS, hpc=args.hpc ,UAPSID= args.uapsid ,CPS_path=args.CPS_path, test_mode=args.test_mode)
    else:
        if args.run_L2:
            script_full_path['IFU']= ifu_scriptGEN(args.infiles, args.config_file, cat_list =cat_list, aps_ids=aps_ids, wlranges=wlranges ,targsrvy=targsrvy,  targclass=targclass,
                mask_aps_ids=mask_aps_ids, area=area, mask_areas=mask_areas, arms_ratio=arms_ratio, headname = args.headname, hname_suffix=args.hname_suffix, log = args.log, aps_ovr =args.aps_ovr, mp_LIFU=args.mp_LIFU, mp_MIFU=args.mp_MIFU, hpc=args.hpc, UAPSID= args.uapsid, patch_file=args.patch_file, seg2d_white_images=seg2d_white_images, CPS_path=args.CPS_path, test_mode=args.test_mode)
        # TBD
        # if args.run_CS:
        #     script_full_path = ifucs_scriptGEN()

    return script_full_path
