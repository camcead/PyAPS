def write_bash(headname, script_filename, commands, JOB_ID_HEADNAME, conf, l1_info=None,
               log=True, logs_path=None, log_prefix=None,
               sbatch_ntasks=None, sbatch_mem=None, sbatch_depends_on=None):
    """
    Write a single-command or multi-command (kiko-ready) bash script for
    one processing stage (or the full OB, when `commands` is a dict).

    sbatch_ntasks, sbatch_mem, sbatch_depends_on : optional, per-stage
        safety-net metadata (added 2 Sep 2026, after a real end-to-end
        SLURM test run). Real submission NEVER goes through `sbatch
        <this-file>` directly -- it always goes through the generated
        *_PyAPS_slurm.sh driver, which passes --ntasks/--mem/--dependency
        explicitly on the sbatch command line (and those CLI flags always
        win over a script's own #SBATCH pragmas, so this can't change real
        submission behaviour). It exists purely because a human WILL,
        during an incident, end up running `sbatch <this-file>` by hand to
        retry a single failed stage -- exactly what happened this session,
        more than once, getting the FERRE --mem flag and the FR-depends-
        on-RVS dependency wrong on the first attempt, purely because
        nothing in the script itself said what those should be. When
        given, sbatch_ntasks/sbatch_mem become real #SBATCH pragmas (so a
        bare `sbatch <this-file>` gets a sane allocation instead of
        SLURM's tiny 1-core/1024MB-per-cpu defaults); sbatch_depends_on is
        documentation only (SLURM's --dependency needs a real, runtime-
        resolved job ID, which can't be hardcoded into a template), a
        comment telling the human what to check before resubmitting this
        stage alone. Only meaningful for per-stage scripts (log_prefix is
        not None) -- the combined kiko-ready script is never `sbatch`-ed
        directly as one job, so it's skipped there.
    """

    # check if logs_path is available
    check_path(logs_path, create=True, verbos=False)

    # Handling the venv status and path
    is_venv = False
    if conf['use_venv'].upper().strip() in ['T', 'TRUE', 'YES', 'Y']:
        check_path(Path(conf['venv_path']), create=False, verbos=True)
        is_venv = True

    with open(script_filename, 'w') as out_script:
        out_script.write("#!/bin/bash \n")
        if log_prefix is not None and (sbatch_ntasks is not None or sbatch_mem is not None or sbatch_depends_on):
            # Real bug caught by the 1-2 Sep 2026 end-to-end SLURM test run:
            # these per-stage scripts have never had #SBATCH pragmas, only
            # the *_PyAPS_slurm.sh driver's explicit sbatch CLI flags carry
            # the real --ntasks/--mem/--dependency. A human resubmitting a
            # single failed stage by hand (`sbatch <this-file>`, exactly
            # what happened during this session's incident response) gets
            # SLURM's bare defaults instead -- caused two real mistakes
            # this session (missing FERRE's --mem, missing FR's dependency
            # on RVS). These pragmas are a safety net for exactly that
            # case; CLI flags on a real sbatch invocation always override
            # a script's own #SBATCH pragmas, so this changes nothing
            # about how aps_runner.py's own driver actually submits jobs.
            if sbatch_ntasks is not None:
                out_script.write(f"#SBATCH --ntasks={int(sbatch_ntasks)}\n")
            if sbatch_mem:
                # sbatch_mem is already a full, valid flag string like
                # '--mem=380GB' (see memory_limit_ferre/memory_limit_IFU
                # above) -- a #SBATCH pragma is just "#SBATCH " + the same
                # flag verbatim, no reformatting needed (or wanted: an
                # earlier version of this code stripped the leading '--',
                # which produced an invalid 'mem=380GB' pragma silently
                # ignored by sbatch -- caught by inspecting a real
                # generated script before committing this).
                out_script.write(f"#SBATCH {sbatch_mem}\n")
            if sbatch_depends_on:
                out_script.write(
                    f"# DEPENDS ON: {sbatch_depends_on}\n"
                    "# This stage reads the above stage's/stages' output "
                    "file(s) directly. Do not resubmit "
                    "this script standalone (`sbatch " + str(script_filename) + "`) "
                    "unless you've confirmed the above already completed "
                    "successfully, or this will fail (typically "
                    "FileNotFoundError on the missing input). SLURM's real "
                    "--dependency needs a runtime job ID, which can't be "
                    "hardcoded here -- see this OB's _PyAPS_slurm.sh for "
                    "the actual dependency chain.\n"
                )
        out_script.write("# PyAPS script generated at: "+ time.strftime("%c")+ "\n")
        out_script.write("# INPUT PARAMETERS, As set by user \n")
        out_script.write("# Note: These PARAMETERS could be modified by the PIPELINE \n")
        out_script.write("export OMP_NUM_THREADS=1 \n")
        out_script.write("export OPENBLAS_NUM_THREADS=1 \n")
        out_script.write("export MKL_NUM_THREADS=1 \n")
        out_script.write("export NUMEXPR_NUM_THREADS=1 \n")
        out_script.write("export HDF5_USE_FILE_LOCKING=FALSE \n")
        # The templates_RVS key of the script_params file in use wins over template_lib of
        # rvs_config.yaml (aps_utils.resolve_rvs_template_lib reads this variable).
        rvs_templates = conf.get('templates_RVS')
        if rvs_templates is not None and str(rvs_templates).strip().upper() not in ('', 'NONE'):
            out_script.write("export PYAPS_RVS_TEMPLATES=%s \n" % shlex.quote(str(rvs_templates).strip()))

        if l1_info is not None:
            for keys in l1_info.keys():
                out_script.write('# %-30s : %s \n' %(keys, l1_info[keys]))

        out_script.write("# \n")
        out_script.write("# \n")

        # if venv is set, we first activate it
        if is_venv:
            out_script.write(f"source {conf['venv_path']} \n")

        ## if commands is a dict of different commands (multiple commands in one script)
        if isinstance(commands, dict):
            print('Generating the all-in-one kiko-ready script file: %s' %(script_filename))

            # Track overall exit status for multiple commands
            out_script.write("OVERALL_EXIT_STATUS=0\n\n")

            for cmd_key in commands.keys():
                if log:
                    log_text = " >& "+str(logs_path.joinpath(f"{JOB_ID_HEADNAME}_{cmd_key}.log"))
                else:
                    log_text = ''

                out_script.write(f"# Running {cmd_key}\n")
                out_script.write(commands[cmd_key] + log_text + "\n")
                out_script.write("CMD_EXIT_STATUS=$?\n")
                out_script.write("if [ $CMD_EXIT_STATUS -ne 0 ]; then\n")
                out_script.write(f"    echo 'ERROR: {cmd_key} failed with exit code '$CMD_EXIT_STATUS >&2\n")
                out_script.write("    OVERALL_EXIT_STATUS=$CMD_EXIT_STATUS\n")
                out_script.write("fi\n\n")

        ## if commands contains a single command
        elif isinstance(commands, str):
            print('Generating the single-task script file: %s' %(script_filename))

            if log and (log_prefix is not None):
                log_text = " >& "+str(logs_path.joinpath(f"{log_prefix}_{JOB_ID_HEADNAME}.log"))
            else:
                log_text = ''

            out_script.write("sleep 30\n")
            out_script.write(commands + log_text + "\n")
            out_script.write("EXIT_STATUS=$?\n")
            out_script.write("\n")
            out_script.write("# Check exit status and log if failed\n")
            out_script.write("if [ $EXIT_STATUS -ne 0 ]; then\n")
            out_script.write("    echo 'ERROR: Command failed with exit code '$EXIT_STATUS >&2\n")
            out_script.write("fi\n")
            out_script.write("\n")

        else:
            sys.exit('Wrong commands format: acceptable formats: dict or str')

        # Deactivate venv if it was activated
        if is_venv:
            out_script.write("deactivate \n")
            out_script.write("\n")

        # Exit with the appropriate status
        out_script.write("# Exit with appropriate status\n")
        if isinstance(commands, dict):
            out_script.write("exit $OVERALL_EXIT_STATUS\n")
        else:
            out_script.write("exit $EXIT_STATUS\n")

    # finally, make it executable
    script_filename.chmod(0o775)

