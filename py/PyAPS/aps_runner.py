def warning_path(aps_path, verbose=True, exit_on_fail=False):
    """
    Check if a file or directory exists and return a warning if it does not.

    Parameters
    ----------
    aps_path : Path or str
        File or directory path to check.
    verbose : bool
        Print status messages.
    exit_on_fail : bool
        If True, exit the program if path does not exist.
        If False (default), just print a warning and return False.

    Returns
    -------
    bool : True if path exists, False otherwise.
    """
    aps_path = Path(aps_path)

    if not aps_path.exists():
        if verbose:
            print(f'PATH/FILE CHECK: WARNING: {aps_path} does not exist')
