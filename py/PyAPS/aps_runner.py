def read_yaml_config(config_file):
    import yaml

    if not Path(config_file).exists():
        sys.exit('No config file found. Check the path: %s' %(config_file))

    _set_pyaps_env_defaults()
    with open(config_file, 'r') as conf_stream:
        try:
            conf =  yaml.safe_load(conf_stream)
            for key, value in conf.items():
                conf[key] = os.path.expanduser(os.path.expandvars(str(value)))
            return conf
        except yaml.YAMLError as exc:
            print(exc)
            return -1


