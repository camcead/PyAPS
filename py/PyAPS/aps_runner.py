def sbatch_guard(jid_var, label, abort=True):
    """
    Bash snippet to check right after `<jid_var>=$(sbatch --parsable ...)`
    that a job ID actually came back, before it's either used as a later
    stage's --dependency or just trusted to have been submitted.

    Without this, a failed sbatch call leaves $<jid_var> empty and the
    generated wrapper script (plain #!/bin/bash, no `set -e`) just carries
    on: for a dependency chain (MOS/IFU L2), later stages end up with a
    malformed `--dependency=afterany:` and fail in a way that's hard to
    trace back to the real cause; for independent jobs (CS), the failure
    is silently invisible - nothing ever reports that module didn't run.

    Parameters
    ----------
    jid_var : str
        The bash variable name holding the sbatch job ID, e.g. 'jid_RR'.
    label : str
        Human-readable job-name label for the error message.
    abort : bool
        True (chained stages): exit the wrapper script immediately, so a
        broken early stage never lets a bogus dependency propagate further.
        False (independent stages, e.g. CS's parallel modules): log and
        continue, so one module failing to submit doesn't stop the others.
    """
    action = 'exit 1' if abort else 'true  # independent job, keep going'
    return (
        'if [[ -z "$%s" || ! "$%s" =~ ^[0-9]+ ]]; then\n'
        '    echo "ERROR: sbatch failed to submit %s (%s=\'$%s\')" >&2\n'
        '    %s\n'
        'fi \n'
    ) % (jid_var, jid_var, label, jid_var, jid_var, action)

