def cs_scriptGEN(infiles, config_file, cat_list=None, aps_ids=None, wlranges=None, mask_aps_ids=None, area=None, mask_areas=None, arms_ratio=None, headname=None,
    hname_suffix=None, log=False, CS_ovr=False, mp = None, hpc=0 ,UAPSID=None, CPS_path=True, test_mode=False):

    print('PyAPS Automatic script Generator for all CS codes')


    #########################################################################################
    ### READ Config file
    conf = read_yaml_config(config_file)


    ### find the running python interpreter
    python_interp = sys.executable


    #########################################################################################
    ### Check inputs

    print('------------------------------------------------------------------------------------')
    print('Checking inputs...')
    print('------------------------------------------------------------------------------------')

    ## As l1_fileinfo may edit the remove one of the files, due to the uncovered wavelength range.
    ## We first blindly run l1_fileinfo with the whole possible wavelength range wlranges=None,
    ## just to get infiles in the right order.

    # We just use the full possible infiles name from this blind run of l1_fileinfo
    l1_info_blind  = l1_fileinfo(infiles, wlranges=None)

    l1_info        = l1_fileinfo(infiles, wlranges=wlranges, arms_ratio = arms_ratio)

    infiles        = l1_info['infiles']
    obsmode        = l1_info['obsmode']
    res_mode       = l1_info['res_mode']
    camera         = l1_info['camera']
    xbin           = l1_info['xbin']
    xbin_str       = [str(xbi) for xbi in xbin]
    ybin           = l1_info['ybin']
    ybin_str       = [str(ybi) for ybi in ybin]
    mode           = l1_info['mode']
    setups         = l1_info['setups']
    srvys          = l1_info['srvys']
    clss           = l1_info['clss']
    wlranges_def   = l1_info['wlranges_def']
    wlranges_out   = l1_info['wlranges']
    resolution     = l1_info['resolution']
    obid           = l1_info['obid']
    obsdate        = l1_info['obsdate']
    arms_ratio     = l1_info['arms_ratio']

    # apply the manual arm-ratio comming from the config file
    arms_ratio = update_arms_ratio(infiles, res_mode, camera, arms_ratio, GR_ratio_HR=float(conf['GR_ratio_HR']), BR_ratio_HR = float(conf['BR_ratio_HR']), GR_ratio_LR=float(conf['GR_ratio_LR']), BR_ratio_LR = float(conf['BR_ratio_LR']))

    ## Generate headname. We also add hname_suffix, if user keen to mark a run with specific setting
    if headname is None:
        headname = '__'.join([Path(i).stem for i in l1_info_blind['infiles']])

    if hname_suffix is not None:
        headname = headname+'_'+str(hname_suffix)

    headname.replace(" ", "")
    print(f"DEBUG: headname has been set to {headname}")

    # test_mode: force a TEST_-prefixed tag and redirect the output dir -
    # see apply_test_mode()'s docstring. No-op when test_mode is False.
    dir_stamp = Path(infiles[0]).parts[-2] if CPS_path else obsdate[0].replace("-", "")
    UAPSID, test_outpath = apply_test_mode(test_mode, UAPSID, conf['CS_RES'], dir_stamp, obid[0])

    # set the unique APS ID to be used as the jobid_name in the script
    if UAPSID is None:
        JOB_ID_HEADNAME=headname
    else:
        JOB_ID_HEADNAME=str(UAPSID).strip()

    #########################################################################################
    ### Generate directories and Paths

    ## Check input PATHs
    PATH_checklist = ['AMY_templates_dir', 'SPACE_exe','AN_neat_null','AN_alfa_exe','AN_neat_exe',\
    'SQ_model', 'FESWI_path', 'FESWI_spectral_windows', 'FESWI_cold_blue_grid',\
    'FESWI_cold_red_grid', 'FESWI_hot_blue_grid', 'FESWI_hot_red_grid', \
    'RRLGV_ephemfile','RRLGV_calibrate_metal', 'RRLGV_calibrate_liu','RRLEW_hr_lines', 'RRLEW_lr_lines']

    for i_p_check in PATH_checklist:
        check_path(Path(conf[i_p_check]))

    #########################################################################################
    ### Generate default output, using PYPAS_RES, osbdate (e.g. 20160903) and obid (e.g. 3153)

    ## if CPS_path is True, then the code extract the path (usually in date YYYYMMDD format from the L1 input path).Otherwise, it will be generated from the OBSDATE
    if test_outpath is not None:
        outpath = test_outpath
    elif CPS_path:
        outpath  = Path(conf['CS_RES']).joinpath(Path(infiles[0]).parts[-2]).joinpath(obid[0])
    else:
        outpath  = Path(conf['CS_RES']).joinpath(obsdate[0].replace("-","")).joinpath(obid[0])
    check_path(outpath, create=True)

    ## Create script path
    scripts_path = outpath.joinpath('scripts')
    check_path(scripts_path, create=True)

    # Create logs path

    logs_path = outpath.joinpath('logs')
    check_path(logs_path, create=True, verbos=False)


    ## Also as CS depends on L2 output path, we need to have the L2 output
    ## path ready - always the REAL L2 dir, even in test_mode: a test CS
    ## run still needs real L2 inputs to read, not a nonexistent test one.
    if CPS_path:
        L2_outpath  = Path(conf['PyAPS_RES']).joinpath(Path(infiles[0]).parts[-2]).joinpath(obid[0])
    else:
        L2_outpath  = Path(conf['PyAPS_RES']).joinpath(obsdate[0].replace("-","")).joinpath(obid[0])
    check_path(L2_outpath, create=False)




    ## Generate output filename of different modules
    final_APS_output = L2_outpath.joinpath((headname+conf['aps_suffix']+conf['fsuffix']).replace(" ",""))
    classfile   =     L2_outpath.joinpath((conf['pref_RR']+headname+conf['fsuffix']).replace(" ",""))
    rvsfile     =     L2_outpath.joinpath((conf['pref_RVS']+headname+conf['fsuffix']).replace(" ",""))
    frfile      =     L2_outpath.joinpath((conf['pref_FR']+headname+conf['fsuffix']).replace(" ",""))

    ##Just add an empty line to separate on-screen report
    print('')


    #########################################################################################
    ### check if final APS product is available (overwrite check)

    CS_output = {}

    CS_output['CS_AMY'] = outpath.joinpath((headname+conf['AMY_suffix']+conf['fsuffix']).replace(" ",""))
    CS_output['CS_SPACE'] = outpath.joinpath((headname+conf['SPACE_suffix']+conf['fsuffix']).replace(" ",""))
    CS_output['CS_AN'] = outpath.joinpath((headname+conf['AN_suffix']+conf['fsuffix']).replace(" ",""))
    CS_output['CS_SQ'] = outpath.joinpath((headname+conf['SQ_suffix']+conf['fsuffix']).replace(" ",""))
    CS_output['CS_FESWI'] = outpath.joinpath((headname+conf['FESWI_suffix']+conf['fsuffix']).replace(" ",""))
    CS_output['CS_RRLGV'] = outpath.joinpath((headname+conf['RRLGV_suffix']+conf['fsuffix']).replace(" ",""))
    CS_output['CS_RRLEW'] = outpath.joinpath((headname+conf['RRLEW_suffix']+conf['fsuffix']).replace(" ",""))

    if (not CS_ovr):
        for cs_keys in CS_output.keys():
            if (CS_output[cs_keys].exists()):
                print('ERROR: Final CS products [%s] already exist. Please set CS_ovr = True if you want to overwrite %s CS product' %(cs_keys))
                return -1

    #########################################################################################
    ### Modify values format , to be sure are ready to be directly inserted into the script

    ## Convert default wavelength ranges from list of lists into a one-line comma-separated string
    if wlranges_out is not None:
        wlranges_str=[]
        for i in range(len(wlranges_out)):
            wlranges_str.append(','.join([str(j) for j in wlranges_out[i]]))
        wlranges_str=' '.join(wlranges_str)
    else:
        wlranges_str = 'None'

    ## as area may contain negative value, we treat it separately, using safe_str
    if area is not None:
        area_str = ','.join([safe_str(i) for i in area])
    else:
        area_str = 'None'

    ## Convert list of list of mask_areas into a one-line comma-separated string
    ## as mask_area may contain negative value, we treat it separately, using safe_str

    if mask_areas is not None:
        mask_areas_str=[]
        for i in range(len(mask_areas)):
            mask_areas_str.append(','.join([safe_str(j) for j in mask_areas[i]]))
        mask_areas_str=' '.join(mask_areas_str)
    else:
        mask_areas_str='None'

    ## Convert lists into one-line comma-separated string
    infiles_str         = key_to_str(infiles,sep=' ')
    aps_ids_str         = key_to_str(aps_ids,sep=',')
    mask_aps_ids_str    = key_to_str(mask_aps_ids,sep=',')
    area_str            = key_to_str(area, sep=',')
    arms_ratio_str      = key_to_str(arms_ratio ,sep=',')


    # for HR mode we double the allocated resource (input mp are set for CS)
    if res_mode[0].upper() == 'HR':
        mp = [mp_i * 2  for mp_i in mp]


    #########################################################################################
